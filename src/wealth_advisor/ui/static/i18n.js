function t(key, vars = {}) {
  const template = LANG === "zh" && ZH[key] ? ZH[key] : key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`));
}

// One / many helper for English plurals; Chinese keys exist for both forms.
function tn(one, many, n, vars = {}) {
  return t(n === 1 ? one : many, { n, ...vars });
}

