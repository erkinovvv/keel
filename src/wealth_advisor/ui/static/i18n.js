function t(key, vars = {}) {
  const template = LANG === "zh" && ZH[key] ? ZH[key] : key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`));
}

// One / many helper for English plurals; Chinese keys exist for both forms.
function tn(one, many, n, vars = {}) {
  return t(n === 1 ? one : many, { n, ...vars });
}

const LOCALE = LANG === "zh" ? "zh-CN" : "en-GB";

function setLanguage(lang) {
  document.cookie = `wa_lang=${lang}; path=/; samesite=strict`;
  location.reload();
}

// Static markup: elements marked data-i18n / data-i18n-placeholder are translated once on load.
document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.textContent.trim()); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.placeholder); });
  document.title = t("Keel");
  const toggle = document.getElementById("langToggle");
  if (toggle) {
    toggle.textContent = LANG === "zh" ? "EN" : "中文";
    toggle.setAttribute("aria-label", LANG === "zh" ? "Switch to English" : "切换到中文");
    toggle.onclick = () => setLanguage(LANG === "zh" ? "en" : "zh");
  }
});
